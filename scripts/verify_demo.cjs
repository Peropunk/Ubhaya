const assert=require('node:assert/strict');
const {chromium} = require(process.env.UBHAYA_PLAYWRIGHT || 'playwright');
(async()=>{
const browser=await chromium.launch({executablePath:process.env.UBHAYA_CHROMIUM,args:['--disable-background-networking']});
const base = process.env.UBHAYA_DEMO_URL || 'http://127.0.0.1:8000';
for(let round=0;round<3;round++){
 const context=await browser.newContext({viewport:{width:1280,height:900}});
 await context.route('**/*',route=>route.request().url().startsWith(base+'/')?route.continue():route.abort());
 const page=await context.newPage();
 const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 const res=await page.goto(base+'/ui/');
 assert.equal(res.status(),200);
 await page.locator('#btn-verify-all').click();
 await page.getByText('Hash matches',{exact:true}).nth(11).waitFor();
 assert.equal(await page.getByText('Hash matches',{exact:true}).count(),12);
 await page.locator('#analyze').click();
 await page.getByText('18 findings',{exact:true}).waitFor();
 assert.equal(await page.locator('[aria-current="page"]').getAttribute('href'),'#statements-section');
 assert(await page.locator('#overview').isHidden());
 await page.getByRole('button',{name:'The files were copied around 22:15',exact:true}).click();
 await page.getByText('Why this finding?',{exact:true}).click();
 await page.getByRole('button',{name:/pc14_events\.csv row 22/}).click();
 await page.locator('#viewer mark').filter({hasText:'16:44:05Z'}).waitFor();
 await page.locator('#viewer-close').click();
 await page.keyboard.press('Escape');
 assert(await page.locator('#detail').isHidden());
 await page.getByRole('button',{name:'Ravi copied the files himself',exact:true}).click();
 await page.getByText('Why this finding?',{exact:true}).click();
 await page.locator('#detail a[href^="#request-"]').click();
 await page.locator('#requests article:target').waitFor();
 assert(await page.locator('#detail').isHidden());
 await page.getByRole('link',{name:'Timeline',exact:true}).click();
 await page.locator('#calibrated').uncheck();
 await page.getByText('The camera ranges allow the corridor sighting to precede the entrance.',{exact:false}).waitFor();
 await page.locator('#calibrated').check();
 await page.getByText('The camera ranges allow the corridor sighting to precede the entrance.',{exact:false}).waitFor({state:'hidden'});
 const alert=page.locator('#timeline article').filter({hasText:'42 seconds apart'});
 const review=alert.locator('form');
 await review.getByLabel('Reviewer',{exact:true}).fill('Demo reviewer');
 await review.getByLabel('Reason',{exact:true}).fill('The repeated scan may be a double tap.');
 await review.getByLabel('Decision',{exact:true}).selectOption('reject');
 await review.getByRole('button',{name:'Save review'}).click();
 await review.getByText('Review recorded').waitFor();
 await page.getByText('Manual time required',{exact:false}).waitFor();
 await page.getByRole('link',{name:'Requests & report',exact:true}).click();
 await page.getByRole('link',{name:'Download PDF',exact:true}).waitFor();
 const report=await page.request.get(base+'/cases/C001/report.json');
 assert.equal(report.status(),200);
 const data=await report.json();
 assert.equal(data.claims.length,18);
 assert.equal(data.artifacts.length,12);
 assert.equal(data.reviews.at(-1).decision,'reject');
 assert.equal(data.manual_time_required.length,1);
 assert(data.audit.ok);
 assert.deepEqual(errors,[]);
 const pdf=await page.request.get(base+'/cases/C001/report.pdf',{timeout:90000});
    assert.equal(pdf.status(),200);
    const bytes=await pdf.body();
 assert.equal(bytes.subarray(0,5).toString(),'%PDF-');
 await context.close();
 console.log('Browser walkthrough '+(round+1)+' passed');
}
await browser.close();
})().catch(err=>{console.error(err);process.exit(1)});
